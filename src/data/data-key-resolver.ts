import type { MissingInputBehavior, TestDataAliasesMap } from "../types/env.types";
import { isVerificationCodeKey } from "./verification-code-role";
import { autoGenerateTestData, type AutoGenerateConfig, type AutoGeneratedDataResult } from "./auto-test-data-generator";

export type DataKeyResolution = {
  status: "resolved" | "missing" | "skipped" | "auto_generated" | "missing_sensitive";
  key: string;
  value?: string;
  source?: string;
  masked?: boolean;
  error?: string;
  autoGenerated?: boolean;
  generatedType?: string;
  generated?: boolean;
  verified?: boolean;
  provenance?: string;
  valueRole?: string;
  oracleSource?: string;
};

type RuntimeEntryInput = { key: string; fieldLabel?: string; value: string; source?: string; generated?: boolean; verified?: boolean; provenance?: string; valueRole?: string; oracleSource?: string };

const SENSITIVE_KEYS = [
  "password", "contrasena", "contraseña", "clave", "pin", "token", "otp", "secret",
  "document", "documento", "cedula", "cédula", "identificacion", "identificación", "rnc",
  "username", "usuario", "company_identifier", "identification_number", "identity_provider",
];

function isSensitiveKey(key: string): boolean {
  const normalized = key.toLowerCase();
  return isVerificationCodeKey(key) || SENSITIVE_KEYS.some(s => normalized.includes(s));
}

/**
 * Generic credential ROLE (never a specific app/project key spelling): a Recording's own
 * valueKey is derived from the recorded field's semantic label (e.g. "contrasena",
 * "entity_1.password"), which never matches the CLI/TestRail-canonicalized spellings below --
 * this maps BOTH onto the same small set of roles the project's already-established secure
 * runtime source (`auth.*` in APP_TEST_DATA_JSON, `QA_RUNTIME_*`/`APP_*` env vars -- see
 * `secure-runtime-runner.ts`) uses. Matched by substring, same vocabulary style as
 * `isSensitiveKey`, never by exact key text.
 */
const CREDENTIAL_ROLE_SOURCES: Record<string, { testDataKey: string; envVar: string }> = {
  otp: { testDataKey: "auth.otp", envVar: "OTP_SECRET" },
  password: { testDataKey: "auth.password", envVar: "APP_PASSWORD" },
  username: { testDataKey: "auth.username", envVar: "APP_USERNAME" },
  company_identifier: { testDataKey: "auth.company_identifier", envVar: "APP_COMPANY_IDENTIFIER" },
};

const CREDENTIAL_ROLE_PATTERNS: Record<string, string[]> = {
  password: ["password", "contrasena", "clave", "pin"],
  username: ["username", "usuario"],
  company_identifier: ["company_identifier", "identification_number", "rnc", "tax_id", "tax_identifier", "business_registration"],
};

export function detectCredentialRole(key: string): keyof typeof CREDENTIAL_ROLE_SOURCES | undefined {
  if (isVerificationCodeKey(key)) return "otp";
  const normalized = normalizeKey(key);
  for (const [role, patterns] of Object.entries(CREDENTIAL_ROLE_PATTERNS)) {
    if (patterns.some((pattern) => normalized.includes(pattern))) return role as keyof typeof CREDENTIAL_ROLE_SOURCES;
  }
  return undefined;
}

export type CredentialRole = keyof typeof CREDENTIAL_ROLE_SOURCES;

/** Bind a field label to its explicit case input without guessing synonyms or suffixes. */
export function runtimeInputKeyForField(field: string, entries: ReadonlyArray<{ key: string; fieldLabel?: string }>): string | undefined {
  const normalizeField = (value: string) => normalizeKey(value).replace(/_+/g, "_").replace(/^_|_$/g, "");
  const normalized = normalizeField(field);
  if (!normalized) return undefined;
  const labeled = entries.filter(entry => entry.fieldLabel && normalizeField(entry.fieldLabel) === normalized);
  if (labeled.length) return labeled.length === 1 ? labeled[0].key : undefined;
  const matches = entries.filter(entry => !entry.fieldLabel && normalizeField(entry.key) === normalized);
  if (matches.length > 0) return matches.length === 1 ? matches[0].key : undefined;
  // Authored labels include grammatical connectors omitted by generated data keys.
  // Preserve every semantic token (including invalid/expired qualifiers) and require uniqueness.
  const withoutConnectors = (value: string) => normalizeField(value).split("_")
    .filter(token => !["de", "del", "el", "la", "los", "las", "of", "the"].includes(token)).join("_");
  const fieldIdentity = withoutConnectors(field);
  if (!fieldIdentity) return undefined;
  const compatible = entries.filter(entry => withoutConnectors(entry.key) === fieldIdentity);
  return compatible.length === 1 ? compatible[0].key : undefined;
}

/** Map an authored credential field to its canonical role only when the case
 * supplies exactly one explicit runtime input for that role. Qualifiers such
 * as "invalid" remain part of the runtime key and are resolved by role later;
 * competing values stay ambiguous and cannot fall through to project secrets. */
export function runtimeCredentialRoleKeyForField(field: string, entries: ReadonlyArray<{ key: string }>): string | undefined {
  const role = detectCredentialRole(field);
  if (!role) return undefined;
  const roleEntries = entries.filter((entry) => detectCredentialRole(entry.key) === role);
  return roleEntries.length === 1 ? CREDENTIAL_ROLE_SOURCES[role].testDataKey : undefined;
}

export function runtimeCredentialRoleInputCountForField(field: string, entries: ReadonlyArray<{ key: string }>): number {
  const role = detectCredentialRole(field);
  return role ? entries.filter((entry) => detectCredentialRole(entry.key) === role).length : 0;
}

/**
 * A launch wizard keys the value of an authored step by its POSITION (`jira_step_N`, `jira_edit_<revision>_N`), so the key
 * says nothing about the field. When step N fills a credential field ("Usuario", "Contraseña", ...), that value is the
 * credential of that role: expose it under the role's canonical key as a sensitive, user-provided credential so the secure
 * resolver and its masking treat it like any other credential. Only a position that matches exactly one entry and one
 * credential-role step is aliased; an existing canonical entry is never overridden, and nothing is guessed by order.
 */
export function aliasPositionalCredentialEntries<T extends RuntimeEntryInput>(
  entries: readonly T[] | undefined,
  steps: ReadonlyArray<{ index: number; label?: string; actionType?: string }>,
): T[] | undefined {
  if (!entries?.length) return entries as T[] | undefined;
  const positional = /^(?:jira_step_|jira_edit_[a-f0-9]{8,}_)(\d+)$/i;
  const aliases: T[] = [];
  for (const step of steps) {
    if (step.actionType && step.actionType !== "action_fill") continue;
    const role = detectCredentialRole(step.label ?? "");
    if (!role) continue;
    const canonical = CREDENTIAL_ROLE_SOURCES[role].testDataKey;
    if (entries.some((entry) => normalizeKey(entry.key) === normalizeKey(canonical))
      || aliases.some((alias) => normalizeKey(alias.key) === normalizeKey(canonical))) continue;
    const labeledCredentials = entries.filter(entry => entry.fieldLabel && detectCredentialRole(entry.fieldLabel) === role);
    const atStep = labeledCredentials.length ? labeledCredentials : entries.filter((entry) => {
      if (entry.fieldLabel) return false;
      const position = positional.exec(entry.key)?.[1];
      return position !== undefined && Number(position) === step.index
        && typeof entry.value === "string" && entry.value.trim() !== "";
    });
    if (atStep.length !== 1) continue;
    aliases.push({ ...atStep[0], key: canonical, source: "user_provided_qa_credentials", sensitive: true } as T);
  }
  return aliases.length ? [...entries, ...aliases] : entries as T[];
}

/**
 * A wizard key keeps the number of the scenario revision that created it, so its suffix is not always the step position
 * (`jira_edit_<rev>_7` can belong to step 9). When the steps that still lack a value and the position-keyed entries still
 * unused are the SAME number, they pair up in ascending order (authoring order is preserved across revisions); the
 * pairing is exposed as `jira_step_<stepIndex>` aliases. Any other counts assign nothing: nothing is guessed.
 */
export function alignOrderedPositionalEntries<T extends RuntimeEntryInput>(
  entries: readonly T[] | undefined,
  steps: ReadonlyArray<{ index: number; label?: string; actionType?: string; hasLiteralValue?: boolean }>,
): T[] | undefined {
  if (!entries?.length) return entries as T[] | undefined;
  const positional = /^(?:jira_step_|jira_edit_[a-f0-9]{8,}_)(\d+)$/i;
  const suffix = (entry: T): number | undefined => {
    const n = positional.exec(entry.key)?.[1];
    return n === undefined ? undefined : Number(n);
  };
  const needing = steps
    .filter((step) => (step.actionType === "action_fill" || step.actionType === "action_select")
      && !step.hasLiteralValue && !detectCredentialRole(step.label ?? ""))
    .map((step) => step.index);
  const usedPositions = new Set(entries.map(suffix).filter((n): n is number => n !== undefined));
  const unmatchedSteps = needing.filter((index) => !usedPositions.has(index)).sort((a, b) => a - b);
  // Positions of credential steps belong to the credential aliasing, never to this pairing.
  const claimedPositions = new Set([
    ...needing,
    ...steps.filter((step) => step.actionType === "action_fill" && detectCredentialRole(step.label ?? "")).map((step) => step.index),
  ]);
  const unusedEntries = entries
    .filter((entry) => !entry.fieldLabel && entry.source !== "user_provided_qa_credentials"
      && !entries.some(auth => detectCredentialRole(auth.key) && auth.value === entry.value)
      && suffix(entry) !== undefined && !claimedPositions.has(suffix(entry)!)
      && typeof entry.value === "string" && entry.value.trim() !== "")
    .sort((a, b) => suffix(a)! - suffix(b)!);
  if (unmatchedSteps.length === 0 || unmatchedSteps.length !== unusedEntries.length) return entries as T[];
  const aliases = unmatchedSteps.map((stepIndex, i) => ({ ...unusedEntries[i], key: `jira_step_${stepIndex}` }) as T);
  return [...entries, ...aliases];
}

/** Return the generic secure-data key for a semantic credential field label. */
export function credentialRoleKeyForField(field: string, runtimeEntries?: RuntimeEntryInput[]): string | undefined {
  // A bare code label is insufficient authority on its own. Bind it only when the
  // caller supplies one explicit verification-code input for this scenario.
  if (["codigo", "code"].includes(normalizeKey(field))) {
    const candidates = runtimeEntries?.filter(entry => isVerificationCodeKey(entry.key) && entry.value.trim()) ?? [];
    return candidates.length === 1 ? "auth.otp" : undefined;
  }
  const role = detectCredentialRole(field);
  return role ? CREDENTIAL_ROLE_SOURCES[role].testDataKey : undefined;
}

// Never reveals any character of the real value -- a masked log line's job is to prove a
// resolution happened, not to help a reader guess the secret from its trailing characters.
function maskValue(_value: string): string {
  return "***";
}

function normalizeKey(key: string): string {
  return key
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9_]/g, "_")
    .trim();
}

function normalizeRuntimeSource(entry: RuntimeEntryInput): string {
  if (entry.source !== "manual_runtime") return entry.source ?? "runtime_context";
  const normalizedKey = normalizeKey(entry.key);
  return normalizedKey.startsWith("auth_")
    || ["username", "password", "otp", "pin", "token", "identity_provider", "app_username", "app_password", "otp_secret"].includes(normalizedKey)
    ? "user_provided_qa_credentials"
    : "explicit_runtime_input";
}

export function resolveDataKey(
  key: string,
  options: {
    testData?: Record<string, unknown>;
    testDataAliases?: TestDataAliasesMap;
    env?: Record<string, string | undefined>;
    missingInputBehavior?: MissingInputBehavior;
    autoGenerateConfig?: AutoGenerateConfig;
    field?: string;
    context?: string;
    overrides?: Record<string, string>;
    suggestedData?: Record<string, string>;
    runtimeEntries?: RuntimeEntryInput[];
    /** Explicit, caller-scoped aliases for preconfigured credential environment names. */
    credentialEnvAliases?: Partial<Record<CredentialRole, string[]>>;
  }
): DataKeyResolution {
  const { testData, testDataAliases, env = {}, missingInputBehavior = "fail", autoGenerateConfig, field, context, overrides, suggestedData, runtimeEntries, credentialEnvAliases } = options as any;
  const normalizedKey = normalizeKey(key);

  // Explicit case-scoped runtime entries are authoritative and retain their
  // provenance through resolution; configured data maps remain lower priority.
  // A TestRail case may store a user-facing placeholder such as {{RNC}}, while
  // discovery interprets that field as the canonical auth.company_identifier
  // role. Bridge those names by the existing generic credential role only when
  // there is exactly one compatible runtime value; never guess among duplicates.
  if (Array.isArray(runtimeEntries)) {
    const hasValue = (entry: RuntimeEntryInput) =>
      entry && typeof entry.key === "string" && typeof entry.value === "string" && entry.value.trim() !== "";
    const runtimeEntry = runtimeEntries.find((entry: RuntimeEntryInput) =>
      entry && typeof entry.key === "string" && normalizeKey(entry.key) === normalizedKey
      && typeof entry.value === "string" && entry.value.trim() !== "",
    );
    const requestedRole = detectCredentialRole(key);
    const roleMatches = requestedRole
      ? runtimeEntries.filter((entry: RuntimeEntryInput) => hasValue(entry) && detectCredentialRole(entry.key) === requestedRole)
      : [];
    const resolvedRuntimeEntry = runtimeEntry ?? (roleMatches.length === 1 ? roleMatches[0] : undefined);
    if (!runtimeEntry && requestedRole === "otp" && roleMatches.length > 1) {
      return { status: "missing_sensitive", key, masked: true, error: "Ambiguous runtime verification-code inputs; supply an explicit valueKey." };
    }
    if (resolvedRuntimeEntry) {
      return {
        status: "resolved",
        key,
        value: resolvedRuntimeEntry.value.trim(),
        source: normalizeRuntimeSource(resolvedRuntimeEntry),
        masked: isSensitiveKey(key),
        ...(resolvedRuntimeEntry.generated !== undefined ? { generated: resolvedRuntimeEntry.generated } : {}),
        ...(resolvedRuntimeEntry.verified !== undefined ? { verified: resolvedRuntimeEntry.verified } : {}),
        ...(resolvedRuntimeEntry.provenance ? { provenance: resolvedRuntimeEntry.provenance } : {}),
        ...(resolvedRuntimeEntry.valueRole ? { valueRole: resolvedRuntimeEntry.valueRole } : {}),
        ...(resolvedRuntimeEntry.oracleSource ? { oracleSource: resolvedRuntimeEntry.oracleSource } : {}),
      };
    }
  }

  // Priority 1: dataOverrides > suggestedValue/default — generic per key, no hardcode
  if (overrides && typeof overrides === "object") {
    const normOverrides = new Map<string,string>();
    for (const [k,v] of Object.entries(overrides as Record<string,string>)) {
      if (v === undefined || v === null) continue;
      const vs = String(v).trim();
      if (!vs) continue;
      normOverrides.set(normalizeKey(k), vs);
      // also keep original case key for direct match
      normOverrides.set(k, vs);
    }
    const hit = normOverrides.get(normalizedKey) ?? (overrides as any)[key] ?? (overrides as any)[normalizedKey];
    if (hit !== undefined && String(hit).trim() !== "") {
      return { status: "resolved", key, value: String(hit).trim(), source: "dataOverrides", masked: isSensitiveKey(key) };
    }
  }
  if (suggestedData && typeof suggestedData === "object") {
    const normSug = new Map<string,string>();
    for (const [k,v] of Object.entries(suggestedData as Record<string,string>)) {
      if (v === undefined || v === null) continue;
      const vs = String(v).trim();
      if (!vs) continue;
      normSug.set(normalizeKey(k), vs);
    }
    const hit = normSug.get(normalizedKey);
    if (hit !== undefined && hit !== "") {
      return { status: "resolved", key, value: String(hit), source: "suggestedValue", masked: isSensitiveKey(key) };
    }
  }
  
  // Priority 1: Direct lookup in APP_TEST_DATA_JSON
  if (testData && key in testData) {
    const value = testData[key];
    if (value !== undefined && value !== null) {
      return {
        status: "resolved",
        key,
        value: String(value),
        source: "APP_TEST_DATA_JSON",
        masked: isSensitiveKey(key)
      };
    }
  }
  
  // Priority 2: Resolve through aliases
  if (testDataAliases && key in testDataAliases) {
    const aliases = testDataAliases[key];
    const aliasList = Array.isArray(aliases) ? aliases : [aliases];
    
    for (const alias of aliasList) {
      if (testData && alias in testData) {
        const value = testData[alias];
        if (value !== undefined && value !== null) {
          return {
            status: "resolved",
            key,
            value: String(value),
            source: `APP_TEST_DATA_JSON (alias: ${alias})`,
            masked: isSensitiveKey(key)
          };
        }
      }
    }
  }
  
  // Priority 3: Generic credential ROLE resolution (username/password/company identifier).
  // Recording's own valueKey is derived from the recorded field's semantic label and never
  // matches a fixed list of literal spellings -- matched by role/substring instead (see
  // `detectCredentialRole`), against the SAME project-configured secure source
  // (`auth.*` in APP_TEST_DATA_JSON) and env vars `secure-runtime-runner.ts` already uses for
  // the TestRail-discovery path. No second credential system, no per-app/key hardcode.
  const credentialRole = detectCredentialRole(key);
  if (credentialRole) {
    const roleSource = CREDENTIAL_ROLE_SOURCES[credentialRole];
    const fromTestData = testData ? testData[roleSource.testDataKey] : undefined;
    if (fromTestData !== undefined && fromTestData !== null && String(fromTestData).trim() !== "") {
      return {
        status: "resolved",
        key,
        value: String(fromTestData).trim(),
        source: `APP_TEST_DATA_JSON (${roleSource.testDataKey})`,
        masked: true
      };
    }
    const configuredEnvVar = [roleSource.envVar, ...(credentialEnvAliases?.[credentialRole] ?? [])]
      .find((envVar: string) => Boolean(env[envVar]));
    const fromEnv = configuredEnvVar ? env[configuredEnvVar] : undefined;
    if (configuredEnvVar && fromEnv) {
      return {
        status: "resolved",
        key,
        value: fromEnv,
        source: configuredEnvVar,
        masked: true
      };
    }
  }

  // Priority 4: Direct env var lookup by normalized key
  const possibleEnvVars = [
    `APP_${normalizedKey.toUpperCase()}`,
    normalizedKey.toUpperCase(),
    key.toUpperCase()
  ];
  
  for (const envVar of possibleEnvVars) {
    const value = env[envVar];
    if (value) {
      return {
        status: "resolved",
        key,
        value,
        source: envVar,
        masked: isSensitiveKey(key)
      };
    }
  }
  
  // Priority 5: Auto-generate if enabled and data is missing
  if (autoGenerateConfig?.enabled && missingInputBehavior === "auto_generate") {
    const autoResult = autoGenerateTestData(key, field, context, autoGenerateConfig);
    
    if (autoResult.generated && autoResult.value) {
      return {
        status: "auto_generated",
        key,
        value: autoResult.value,
        source: "auto_generated",
        masked: autoResult.sensitive,
        autoGenerated: true,
        generatedType: autoResult.type
      };
    }
    
    if (autoResult.sensitive && !autoResult.generated) {
      return {
        status: "missing_sensitive",
        key,
        error: `Sensitive data key "${key}" cannot be auto-generated. Reason: ${autoResult.reason || "policy_restriction"}`,
        masked: true
      };
    }
  }
  
  // Priority 6: Handle missing based on behavior
  if (missingInputBehavior === "skip") {
    return {
      status: "skipped",
      key,
      error: `Data key "${key}" not found, skipped due to missingInputBehavior=skip`
    };
  }
  
  // Check if this is a sensitive key that's missing
  if (isSensitiveKey(key)) {
    return {
      status: "missing_sensitive",
      key,
      error: `Missing sensitive test data value for key "${key}". Set APP_TEST_DATA_JSON.${key} or APP_${key.toUpperCase()}`
    };
  }
  
  return {
    status: "missing",
    key,
    error: `Missing test data value for key "${key}". Set APP_TEST_DATA_JSON.${key} or APP_${key.toUpperCase()}`
  };
}

export function formatDataKeyForLog(resolution: DataKeyResolution): string {
  if (resolution.status !== "resolved" && resolution.status !== "auto_generated") {
    return `[data-resolver] key="${resolution.key}" status="${resolution.status}" ${resolution.error ? `error="${resolution.error}"` : ""}`;
  }
  
  const valueDisplay = resolution.masked || resolution.source === "dataOverrides"
    ? maskValue(resolution.value!)
    : resolution.value;
  const sourceInfo = resolution.autoGenerated 
    ? `source="${resolution.source}" type="${resolution.generatedType || "unknown"}"`
    : `source="${resolution.source}"`;
  return `[data-resolver] key="${resolution.key}" ${sourceInfo} value="${valueDisplay}"`;
}
